import pkg from 'pg';
const { Client } = pkg;
import dotenv from 'dotenv';

dotenv.config({ path: '.env.local' });

const connectionString = process.env.SUPABASE_POSTGRES_URL_NON_POOLING.replace('?sslmode=require', '');
if (!connectionString) {
    console.error("Missing SUPABASE_POSTGRES_URL_NON_POOLING");
    process.exit(1);
}

const client = new Client({
    connectionString,
    ssl: { rejectUnauthorized: false }
});

async function setup() {
    try {
        await client.connect();
        console.log("Connected to PostgreSQL");

        const sql = `
            CREATE TABLE IF NOT EXISTS contacts (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                office_name TEXT,
                contact_name TEXT,
                email TEXT,
                a BOOLEAN DEFAULT false,
                b BOOLEAN DEFAULT false,
                c BOOLEAN DEFAULT false,
                who TEXT,
                mailing TEXT,
                street_address TEXT,
                city TEXT,
                state TEXT,
                zip TEXT,
                phone1 TEXT,
                phone2 TEXT,
                phone3 TEXT,
                phone4 TEXT,
                website TEXT,
                comments TEXT,
                pinned_note TEXT,
                specialties TEXT[] DEFAULT '{}',
                notes JSONB DEFAULT '[]'::jsonb,
                created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
            );

            -- Ensure RLS is enabled
            ALTER TABLE contacts ENABLE ROW LEVEL SECURITY;

            -- Drop policy if it exists so we can recreate it
            DO $$
            BEGIN
              IF EXISTS (
                SELECT 1 FROM pg_policies 
                WHERE schemaname = 'public' 
                AND tablename = 'contacts' 
                AND policyname = 'Allow anon all'
              ) THEN
                DROP POLICY "Allow anon all" ON contacts;
              END IF;
            END
            $$;

            -- Create policy to allow public access for all operations
            CREATE POLICY "Allow anon all" ON contacts FOR ALL USING (true) WITH CHECK (true);
        `;
        
        await client.query(sql);
        console.log("Table and RLS schema configured successfully!");

    } catch (e) {
        console.error("Error setting up DB:", e);
    } finally {
        await client.end();
    }
}

setup();
